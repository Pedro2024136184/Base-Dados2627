SELECT *
FROM EMP
WHERE SAL > 3000;

SELECT C.NEMP, C.NOME, E.NEMP, E.NOME
FROM EMP E, EMP C
WHERE E.ENCAR = C.NEMP;

SELECT E.NOME, E.FUNCAO, D.NOME
FROM EMP E, DEP D
WHERE E.NDEP = D.NDEP
ORDER BY D.NOME ASC, E.NOME DESC;

SELECT NOME, SAL, NDEP
FROM EMP
WHERE NOME LIKE 'C% M%'
  AND SAL < 1000;

SELECT E.NOME, E.DATA_ENTRADA, D.NOME, D.LOCAL
FROM EMP E, DEP D
WHERE E.NDEP = D.NDEP
  AND E.SAL > 1000;

SELECT DISTINCT D.ESCALAO, E.FUNCAO
FROM EMP E, DESCONTOS D
WHERE E.SAL BETWEEN D.SALINF AND D.SALSUP
ORDER BY D.ESCALAO, E.FUNCAO;

SELECT E.NOME, E.FUNCAO, E.SAL, D.ESCALAO, D.SALINF, D.SALSUP
FROM EMP E, DESCONTOS D
WHERE E.SAL BETWEEN D.SALINF AND D.SALSUP
  AND (D.ESCALAO = 3 OR D.ESCALAO = 5)
ORDER BY E.NOME ASC;

SELECT E.NOME, E.FUNCAO, E.SAL, DP.NOME, D.ESCALAO, D.SALINF, D.SALSUP
FROM EMP E, DESCONTOS D, DEP DP
WHERE E.SAL BETWEEN D.SALINF AND D.SALSUP
  AND E.NDEP = DP.NDEP
  AND D.ESCALAO IN (3, 5)
ORDER BY E.NOME ASC;

SELECT E.NOME, E.FUNCAO, E.SAL, D.LOCAL
FROM EMP E, DEP D
WHERE E.NDEP = D.NDEP
  AND UPPER(D.LOCAL) IN ('BOSTON', 'CHICAGO')
  AND E.SAL > 1000;

SELECT E.NOME, E.FUNCAO, D.ESCALAO, DP.NOME
FROM EMP E, DESCONTOS D, DEP DP
WHERE E.SAL BETWEEN D.SALINF AND D.SALSUP
  AND E.NDEP = DP.NDEP
  AND UPPER(E.FUNCAO) NOT IN ('ANALISTA', 'CONTABILISTA')
ORDER BY D.ESCALAO DESC;

SELECT E.NOME, E.FUNCAO, D.NOME
FROM EMP E, DEP D
WHERE E.NDEP (+) = D.NDEP
ORDER BY D.NOME ASC, E.NOME DESC;